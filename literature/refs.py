def bibtex():
    out = []
    for r in REFS:
        out.append(f"@misc{{{r['key']},\n  author = {{{r['authors'].replace(', ', ' and ')}}},\n  title = {{{r['title']}}},\n"
                   f"  howpublished = {{{r['venue']}}},\n  year = {{{r['year']}}},\n  url = {{{r['url']}}}\n}}\n")
    return "\n".join(out)


def ieee(r):
    return f"{r['authors']}, \"{r['title']},\" {r['venue']}, {r['year']}. [Online]. Available: {r['url']}"


